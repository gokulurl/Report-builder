const enc = (svg) => 'data:image/svg+xml,' + encodeURIComponent(
  svg.replace(/ style="[^"]*"/, ' stroke-width="1.6"').replace(/ aria-hidden="true"| data-slot="icon"/g, ''),
);
let css = `// GENERATED by gen-hero-icons.mjs: Material icon names drawn as Registration v2's Heroicons (outline).\n` +
  `// The <mat-icon> keeps its ligature text (Angular still binds it); app.ts copies that text into data-i,\n` +
  `// and the glyph is painted as a mask in the text colour. Unmapped names fall back to the font.\n`;
const missing = [];
for (const [name, hero] of Object.entries(MAP)) {
  const svg = svgs['hero' + hero];
  if (!svg) { missing.push(`${name}→${hero}`); continue; }
  css += `.mat-icon[data-i='${name}'] { --hi: url("${enc(svg)}"); }\n`;
}
// Filled star for a favourite that is on: same outline, filled with the text colour.
const starFilled = svgs.heroStar.replace('fill="none"', 'fill="black"');
css += `.mat-icon[data-i='star'] { --hi: url("${enc(starFilled)}"); }\n`;
// Only mapped names get painted; anything else keeps the icon font, so a miss shows a glyph, not a square.
const sel = Object.keys(MAP).filter((n) => svgs['hero' + MAP[n]]).map((n) => `.mat-icon[data-i='${n}']`).join(',\n');
css += `${sel} {\n  -webkit-text-fill-color: transparent; background-color: currentColor;\n` +
  `  -webkit-mask: var(--hi) center / contain no-repeat; mask: var(--hi) center / contain no-repeat;\n}\n`;
writeFileSync(out, css);
console.log('icons:', Object.keys(MAP).length, 'missing:', missing.join(', ') || 'none');
